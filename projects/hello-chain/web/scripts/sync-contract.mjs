// Generates src/lib/contract.ts from the Foundry artifact and deployments/*.json.
// Run: pnpm sync:contract (after `forge build` and a deploy).
import { readFileSync, readdirSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const contracts = resolve(here, "../../contracts");
const artifactPath = join(contracts, "out/Guestbook.sol/Guestbook.json");
const deploymentsDir = join(contracts, "deployments");
const outPath = resolve(here, "../src/lib/contract.ts");

if (!existsSync(artifactPath)) {
  console.error(`Missing ${artifactPath}. Run \`forge build\` in contracts/ first.`);
  process.exit(1);
}

const { abi } = JSON.parse(readFileSync(artifactPath, "utf8"));

const addresses = {};
const blocks = {};
if (existsSync(deploymentsDir)) {
  for (const file of readdirSync(deploymentsDir).filter((f) => /^\d+\.json$/.test(f)).sort()) {
    const chainId = Number(file.replace(".json", ""));
    const { address, blockNumber } = JSON.parse(readFileSync(join(deploymentsDir, file), "utf8"));
    if (!/^0x[0-9a-fA-F]{40}$/.test(address ?? "")) {
      console.error(`Invalid address in deployments/${file}: ${JSON.stringify(address)}`);
      process.exit(1);
    }
    addresses[chainId] = address;
    blocks[chainId] = blockNumber ?? 0;
  }
}

const addrLines = Object.entries(addresses).map(([id, a]) => `  ${id}: "${a}",`).join("\n");
const blockLines = Object.entries(blocks).map(([id, b]) => `  ${id}: BigInt(${Number(b)}),`).join("\n");

const source = `// GENERATED by web/scripts/sync-contract.mjs. DO NOT EDIT.
// Regenerate with \`pnpm sync:contract\` after \`forge build\` and a deploy.

export const guestbookAbi = ${JSON.stringify(abi, null, 2)} as const;

export const guestbookAddress: Record<number, \`0x\${string}\`> = {
${addrLines}
};

/** Block at (or just before) deployment; start of the feed's event scan. */
export const guestbookDeployBlock: Record<number, bigint> = {
${blockLines}
};
`;

writeFileSync(outPath, source);
console.log(`Wrote ${outPath} (${Object.keys(addresses).length} deployment(s))`);
